#!/usr/bin/env python3
"""
Quick check of the claims of the paper from the code and the stored results (a few minutes on one core).

    python3 verify.py            # everything below
    python3 verify.py --skip-ea  # without the EA-equivalence re-checks (section 6)

Sections:
 1. types/: the 299 types (n = 10) and the n = 6, 8 tables are regenerated by enumerate.py.
 2. proofs/: W spaces of all 299 types regenerated by sym_setup.py (equal to the ones used by the searches,
    engine/W3); proof criteria (proofs10.py), Wong (wong10.py), dual lemma D (lemma_dual.py), BBF bound (bbf.py),
    lemma56 (check56.py); the 280 exclusion certificates (check_certificates.py, independent checker); master
    table regenerated (master_table.py) with its summary counts.
 3. engine/: sym10.c and sym10f73.c compiled; type 231 searched exhaustively (same nodes and leaves as the
    server run); the 12 forced-prefix type-73 validation runs (same nodes, leaves and pruned checkpoints as the
    stored runs; sym10 and sym10f73 give identical output).
3b. the dedicated solvers: type-24 solver at n = 6 (Gold and Kim, 32 leaves) and planted tests at n = 10;
    type-47 solvers (stage2g, stage2i) at n = 6 (the 6 Gold completions).
 4. stored search results: type 24 (4,096 jobs, 3 leaves), type 47 (all 8,056 slices covered, no leaf),
    type 73 (rerun agrees with the first run piece by piece; 4,536 leaves, EA results for all of them),
    fingerprint-gap reruns (fpgap, complete).
 5. the 4 new classes: APN, degree 2, ortho-derivative invariants as in the paper; type 64 contains exactly
    16 of the 29 known classes (iso64.py).
 6. EA certificates recomputed (exact search with explicit (L1, L2), certificate re-checked) for the 3 type-24
    leaves, one leaf of each of the 24 type-73 classes, and a few type-231 leaves (a sample: the full EA re-checks
    of all leaves are separate long runs, see README "Three ways to check").
 7. independent checks of stored certificates and representatives: Table II recount, Kim's class over F_8 (n = 6),
    type-47 brute force at n = 6, type-47 stage 1 regenerated, plane action of type 24, M of the new classes.
Every subprocess runs in a sanitized environment (printed at the start); solver options are passed explicitly.
Exit status 1 if any check fails.
"""
