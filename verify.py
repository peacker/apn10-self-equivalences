def inv_of(F):
    return hashlib.sha1(repr(ortho_invariant(F, 10)).encode()).hexdigest()[:16]


def is_apn(F):
    X = np.arange(len(F))
    return all(np.bincount(F ^ F[X ^ a], minlength=len(F)).max() <= 2 for a in range(1, len(F)))


